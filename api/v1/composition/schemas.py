# app/api/v1/composition/schemas.py
"""Pydantic-схемы ответов раздела «Состав проекта» (Слой 2.1, read-only).

Здесь только Response-модели: оба эндпоинта Слоя 2.1 — GET, тела запроса
не принимают. Request-схема (финальный список состава для синхронизации)
появится в Слое 2.2 вместе с POST-эндпоинтом.

Схемы читаются напрямую из ORM-объектов (ORM-модели справочников и
read-only VProjectComposition), поэтому у всех включён режим
from_attributes: pydantic собирает модель из атрибутов объекта, а не
из словаря.

Стиль конфигурации — model_config = ConfigDict(...) (pydantic v2), а не
устаревший вложенный class Config: типобезопасно (ConfigDict — TypedDict,
mypy проверяет ключи) и без deprecation-предупреждений (правило 16).
"""
from pydantic import BaseModel, ConfigDict, Field, computed_field, field_validator


# ---------------------------------------------------------------------------
# Схемы для GET /refs — справочник для формы редактора состава.
#
# Предметная механика (подтверждена пользователем): одна запись
# marka_types = аббревиатура + КОНКРЕТНАЯ стадия. АР(РД) и АР(ПД) — две
# РАЗНЫЕ записи с разными id и одинаковым code='АР'. Поэтому у каждой
# марки ровно одна стадия (stage) и, после фильтра «ровно один отдел»
# (вариант B), ровно один отдел (department) — оба поля единичные и
# обязательные, не списки и не Optional.
#
# Группировку по коду (ГИП вводит «АР» → показать АР-РД и АР-ПД на выбор)
# делает React локально по полю code — серверу об этом знать не нужно.
# ---------------------------------------------------------------------------


class StageRefOut(BaseModel):
    """Стадия марки (ПД/РД/…). Единственная допустимая стадия записи."""

    id: int
    stage_name: str

    model_config = ConfigDict(from_attributes=True)


class DepartmentRefOut(BaseModel):
    """Отдел-исполнитель марки. Единственный (гарантирует фильтр B)."""

    id: int
    code: str
    name: str

    model_config = ConfigDict(from_attributes=True)


class MarkaRefOut(BaseModel):
    """Запись справочника марок для формы: марка + её стадия + её отдел.

    department и stage обязательны: в /refs попадают только марки с ровно
    одним отделом (фильтр B в сервисе) и определённой стадией. Марка без
    отдела или без стадии в справочник не выдаётся — выбрать её в форме
    нельзя (это осознанное следствие стратегии «строго один отдел»).
    """

    marka_type_id: int
    code: str
    name: str
    # Вложенные объекты (не id): фронт сразу получает коды/имена для
    # отображения в dropdown и превью, без второго запроса за деталями.
    department: DepartmentRefOut
    stage: StageRefOut

    model_config = ConfigDict(from_attributes=True)


# ---------------------------------------------------------------------------
# Схема для GET /{project_id} — текущий состав проекта (наполнение превью).
#
# Узкий контракт (решение D3): только поля, которые реально потребляет
# «корзина» — бизнес-ключ (marka_type_id, stage_id, department_id) для
# add/remove и последующей синхронизации, человекочитаемые коды/имена для
# показа, composition_id как identity строки, и производный флаг
# has_mark_sets. project_id/project_code не дублируем (проект известен из
# URL), parent_department_name/department_code для плоского превью не нужны.
# ---------------------------------------------------------------------------


class CompositionRowOut(BaseModel):
    """Строка текущего состава проекта для превью редактора.

    Источник — read-only VProjectComposition (проекция v_project_composition).
    Флаг has_mark_sets выводится из documents_count: он управляет Защитой A
    на фронте (есть комплекты → крестик удаления неактивен, чтобы каскадное
    удаление строки состава не снесло работу бюро).
    """

    # Identity строки состава: по нему React адресует удаление, сервер —
    # сверяет присланное состояние с текущим при синхронизации (Слой 2.2).
    composition_id: int

    # Бизнес-ключ (часть unique_composition) — ядро add/remove и POST-sync.
    marka_type_id: int
    stage_id: int
    department_id: int

    # Человекочитаемые поля для отображения в превью.
    marka_code: str
    marka_name: str
    stage_name: str
    department_name: str

    # Служебный источник для has_mark_sets. Field(exclude=True): поле
    # читается из VProjectComposition.documents_count (нужно для расчёта
    # флага), но НЕ сериализуется — в JSON-ответе его нет, наружу уходит
    # только производный has_mark_sets. default=0 — страховка, если
    # источник почему-то не отдал значение (трактуем как «нет комплектов»).
    documents_count: int = Field(default=0, exclude=True)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def has_mark_sets(self) -> bool:
        """Есть ли под строкой физические комплекты (project_mark_sets).

        True → у строки есть документы → удалять её нельзя (Защита A):
        каскад project_mark_sets.composition_id снёс бы работу бюро.
        Фронт по этому флагу гасит крестик удаления в корзине.
        """
        # Бизнес-правило «есть комплекты» = счётчик документов положителен.
        return self.documents_count > 0

    model_config = ConfigDict(from_attributes=True)


# ---------------------------------------------------------------------------
# Схемы запроса для POST /{project_id} — синхронизация состава (Слой 2.2).
#
# Решение X (синхронизация): клиент шлёт ФИНАЛЬНЫЙ желаемый состав, сервер
# приводит БД к нему (вычисляет разницу to_delete/to_insert).
#
# Многоотдельные марки: одна марка (marka_type_id) может выпускаться
# несколькими отделами (department_markas — M:M, PK department+marka). Поэтому
# marka_type_id больше НЕ определяет отдел однозначно, и элемент состава — это
# ПАРА (marka_type_id, department_id): ГИП выбирает конкретный отдел в форме.
# stage_id по-прежнему НЕ шлётся — сервер выводит его из marka_to_stage (одна
# стадия на марку; инвариант данных, схемой не гарантируется — проверяется в
# сервисе). project_id — из URL.
# ---------------------------------------------------------------------------


class CompositionItemIn(BaseModel):
    """Один элемент желаемого состава: пара «марка + отдел-исполнитель».

    Пара, а не одиночный marka_type_id: многоотдельная марка (напр. ТР,
    marka_type_id=81, отделы ГЕНП+СТР) закреплена за несколькими отделами в
    department_markas, и ГИП выбирает, КАКОЙ отдел выпускает её в этом проекте.
    Отдел приходит от клиента (он его выбрал), стадию сервер выводит сам.

    Валидность пары (отдел действительно вправе выпускать эту марку) проверяет
    сервис по department_markas — здесь только форма, без бизнес-проверок.
    """

    marka_type_id: int
    department_id: int

    model_config = ConfigDict(from_attributes=True)


class CompositionSyncIn(BaseModel):
    """Желаемый финальный состав проекта — список пар марка+отдел (Решение X).

    items — пары (marka_type_id, department_id), которые должны быть в составе
    после сохранения. Пустой список допустим: «очистить состав» (удалить все
    строки, с проверкой Защиты A по каждой — если под строкой есть комплекты,
    операция будет отвергнута сервисом). Дубли пар молча удаляются валидатором
    (одна и та же пара не может быть в составе дважды — unique_composition всё
    равно отверг бы второй INSERT).
    """

    items: list[CompositionItemIn]

    model_config = ConfigDict(from_attributes=True)

    @field_validator("items")
    @classmethod
    def _deduplicate(cls, value: list[CompositionItemIn]) -> list[CompositionItemIn]:
        """Молча убирает дубли ПАР, сохраняя порядок первого появления.

        Дедуп теперь по паре (marka_type_id, department_id), а НЕ по одному
        marka_type_id: одна марка под разными отделами — это РАЗНЫЕ валидные
        строки состава (многоотдельность), терять их нельзя. Дублем считается
        полное совпадение пары.

        dict.fromkeys (как в старой версии) не подходит: CompositionItemIn
        нехешируем. Дедупим вручную через set хешируемых кортежей-ключей, а
        сами объекты добавляем в порядке первой встречи (порядок может нести
        смысл — последовательность добавления марок ГИПом; для синхронизации в
        итоге неважен, но сохранить его честнее, чем терять).
        """
        seen: set[tuple[int, int]] = set()
        unique: list[CompositionItemIn] = []
        for item in value:
            # Кортеж-ключ пары — хешируем для проверки на повтор.
            pair = (item.marka_type_id, item.department_id)
            if pair not in seen:
                seen.add(pair)
                unique.append(item)
        return unique


# ---------------------------------------------------------------------------
# Схема для GET /project-search — автодополнение шифра проекта (вход B).
#
# ГИП на странице создания состава вводит шифр; автодополнение отдаёт
# подходящие проекты. Путь 2: элемент несёт всё нужное фронту сразу —
# project_id (по нему откроется корзина), code/title (показать в dropdown)
# и has_composition (есть ли уже состав → создание или редактирование).
# Отдельный резолвер не нужен: выбрав элемент, фронт уже всё знает.
# ---------------------------------------------------------------------------


class ProjectSearchOut(BaseModel):
    """Элемент автодополнения шифра проекта (вход B)."""

    project_id: int
    code: str
    title: str
    # Есть ли у проекта хотя бы одна строка состава. Фронт по флагу решает:
    # True → откроется на редактирование (превью с марками); False → пустое
    # превью (создание с нуля). Граница create/edit стёрта — оба пути ведут
    # в одну корзину.
    has_composition: bool

    model_config = ConfigDict(from_attributes=True)