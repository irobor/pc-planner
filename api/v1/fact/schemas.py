# app/api/v1/fact/schemas.py
"""Pydantic-схемы границы API факта — контракт с React-островом главной.

Правила живут в rules.py, работа с БД — в service.py; здесь только то,
что уходит в матрицу инженера и приходит от неё.

Устройство ответа то же, что у сетки начальника (planning/schemas.py):
плоские слои rows / days / cells с общим ключом, а не вложенное дерево.
Разница одна — инженер всегда один, поэтому employee_id в слоях нет:
он был бы одинаковым в каждом элементе.

Вердикт дня (DayOut.state) и допустимость шифра (FactRowOut.allows_fact)
считает сервер. Фронт их не вычисляет — иначе правила оказались бы
записаны дважды, на двух языках, и однажды разошлись бы.

Отказ записи (409) отдаётся строкой в detail, без отдельной схемы:
операция всегда одна, и фронту достаточно показать текст и перечитать
месяц — перечитывание заодно подтянет то, из-за чего пришёл отказ
(например, неявку, внесённую табельщицей после загрузки страницы).
"""

from datetime import date
from typing import Optional

from pydantic import BaseModel, ConfigDict, Field

from app.api.v1.fact.rules import FactDayState, MarkAction

# ---------------------------------------------------------------------------
# Ответ GET /api/fact/window — лента инженера от якорного дня.
# ---------------------------------------------------------------------------


class FactRowOut(BaseModel):
    """Строка матрицы — шифр.

    Попадает в матрицу, если в этом месяце у инженера по шифру есть план
    или факт, либо он назначен исполнителем шифра в статусе из
    FACT_STATUS_IDS. Строки, добавленные через поиск, живут только в
    браузере до первой отметки — сервер о них не знает.
    """

    mark_set_id: int
    marka_full: str
    status_id: int

    # Инженер — исполнитель шифра. False: строка пришла из ячеек, то
    # есть это чужой шифр (на макете — пометка «не мой»).
    is_executor: bool

    # Можно ли отмечать факт по этому шифру (set_allows_fact). False у
    # выпущенного комплекта: строка видна ради истории, но клетки в ней
    # не кликаются даже в открытые дни (на макете — пометка «закрыт»).
    allows_fact: bool

    model_config = ConfigDict(from_attributes=True)


class FactDayOut(BaseModel):
    """Состояние дня инженера — один элемент на каждую дату месяца.

    По нему фронт гасит столбец, ставит букву табеля в строку «Табель»
    и решает, кликабелен ли день. Кликабелен только state == "open".
    """

    work_date: date
    state: FactDayState

    # Буква табеля (Б, ОТ, К, НН, ПР...) — только при state == "absence".
    tab_letter: Optional[str] = None

    # Тип нерабочего дня (WEEKEND / HOLIDAY) — только при "nonwork".
    day_type_code: Optional[str] = None

    model_config = ConfigDict(from_attributes=True)


class FactCellOut(BaseModel):
    """Заполненная клетка на пересечении шифра и дня.

    Отдаются только непустые. Пара флагов даёт три вида отображения, те
    же, что в сетке начальника: только план — синяя полоса, план и
    факт — факт по плану, только факт — факт вне плана.
    """

    mark_set_id: int
    work_date: date
    has_plan: bool
    has_fact: bool

    model_config = ConfigDict(from_attributes=True)


class FactWindow(BaseModel):
    """Полный ответ ленты: дни от якоря, 14 назад и 28 вперёд.

    Лента, а не календарный месяц: в любой день — и 1-го числа тоже —
    на экране сегодня, предыдущий рабочий день, две недели истории и
    четыре недели плана.

    Все даты считает сервер, включая якоря соседних положений ленты.
    Браузер дат не складывает: при UTC+3 toISOString() сдвигает дату на
    сутки — ловушка, на которой уже спотыкались.
    """

    # День, от которого построена лента (без параметра — сегодня).
    anchor: date

    # Якоря для стрелок «‹» и «›» — сдвиг на неделю. None — дальше
    # лента ушла бы за край производственного календаря, стрелка гаснет.
    prev_anchor: Optional[date] = None
    next_anchor: Optional[date] = None

    # Первый и последний день ленты (включительно).
    date_from: date
    date_to: date

    # Серверное «сегодня» — для подсветки столбца и кнопки «Сегодня».
    today: date

    # Начало окна ОТМЕТКИ (предыдущий рабочий день). Не путать с
    # границами ленты: это про то, какие дни кликабельны. Фронт берёт
    # кликабельность из days[].state, поле — для подсказки.
    mark_window_from: date

    # Края заполненного production_calendar.
    horizon_from: date
    horizon_to: date

    rows: list[FactRowOut]
    days: list[FactDayOut]
    cells: list[FactCellOut]

    model_config = ConfigDict(from_attributes=True)


# ---------------------------------------------------------------------------
# POST /api/fact/mark — отметка одного дня.
# ---------------------------------------------------------------------------


class MarkIn(BaseModel):
    """Клик инженера по клетке (шифр, день).

    employee_id НЕ передаётся: сервер берёт инженера из current_user.
    Подменой id в запросе отметить факт за другого нельзя.
    """

    # gt=0: id из БД положительны; 0 или отрицательное число — мусор,
    # его лучше отсечь 422 до обращения к базе.
    mark_set_id: int = Field(gt=0)
    work_date: date

    model_config = ConfigDict(from_attributes=True)


class MarkResult(BaseModel):
    """Результат отметки: что сделано и свежее состояние дня.

    Хватает, чтобы перерисовать один столбец без повторного GET месяца.
    """

    # insert — отметка создана, move — перенесена с другого шифра,
    # noop — клик по собственной отметке, ничего не изменилось.
    # reject сюда не попадает: отказ приходит кодом 409.
    action: MarkAction

    day: FactDayOut

    # Все непустые клетки этой даты. При переносе меняются две клетки —
    # старая теряет факт, новая получает, — поэтому отдаётся столбец
    # целиком, а не одна клетка.
    cells: list[FactCellOut]

    # Строка шифра, по которому поставлена отметка. Нужна, когда шифр
    # пришёл из поиска и строки у фронта не было: после отметки она
    # становится серверной. В остальных случаях фронт её просто
    # перезапишет теми же данными.
    row: FactRowOut

    model_config = ConfigDict(from_attributes=True)


# ---------------------------------------------------------------------------
# GET /api/fact/mark-sets — поиск шифра для «+ добавить шифр».
# ---------------------------------------------------------------------------


class MarkSetFound(BaseModel):
    """Шифр, найденный поиском.

    Минимальная длина строки поиска и предел выдачи задаются в
    service.py и проверяются в routes.py, до обращения к БД.
    """

    id: int
    marka_full: str

    # Подразделение-владелец шифра (project_composition.department_id) —
    # на макете «ТЕХН · Технологическое бюро».
    department_code: str
    department_name: str

    # Близость к инженеру — ключ сортировки выдачи:
    # 0 — его бюро, 1 — его отдел, 2 — остальная организация.
    proximity: int = Field(ge=0, le=2)

    model_config = ConfigDict(from_attributes=True)
